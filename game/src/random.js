// TIDEWARDEN — tiny seeded random number generator (mulberry32).
// Screenshot scenes and wave layouts draw from a seeded generator so a
// given seed always plays the same night, which keeps the screenshots
// deterministic.

export function makeRng(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function pick(rng, list) {
  return list[Math.floor(rng() * list.length)];
}

export function range(rng, lo, hi) {
  return lo + rng() * (hi - lo);
}

export function intIn(rng, lo, hi) {
  return lo + Math.floor(rng() * (hi - lo + 1));
}

// Fisher-Yates shuffle that draws only from the seeded generator, so a
// shuffled spawn order is reproducible for a given seed.
export function shuffle(rng, list) {
  const out = list.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
